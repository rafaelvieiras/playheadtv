func assertContiguous(t *testing.T, entries []domain.EpgEntry) {
	t.Helper()
	for i := 1; i < len(entries); i++ {
		if entries[i].StartAt != entries[i-1].EndAt {
			t.Errorf("hole between entry %d and %d: %v -> %v", i-1, i,
				time.UnixMilli(entries[i-1].EndAt), time.UnixMilli(entries[i].StartAt))
		}
	}
}

func TestResetSchedule_ResetsOnlyItsChannels(t *testing.T) {
	f := continuousSetup(t)
	ctx := context.Background()
	f.createChannelWithNumber(t, "chan2", 2, "UTC")
	f.createSchedule(t, "sched2")
	f.assignChannelSchedule(t, "chan2", "sched2")
	f.createContinuousScheduleItem(t, "cont2", "sched2", "rot")

	mat := New(f.db, 4*time.Hour)
	mat.SetFreezeMargin(time.Hour)
	if err := mat.Run(ctx); err != nil {
		t.Fatal(err)
	}
	shift := int64(90 * 60 * 1000)
	if err := f.db.Exec(ctx, "UPDATE epg_entry SET start_at = start_at - ?, end_at = end_at - ?", shift, shift); err != nil {
		t.Fatal(err)
	}
	var before2 []string
	if err := f.db.Query(ctx, &before2, "SELECT id FROM epg_entry WHERE channel_id = 'chan2' ORDER BY start_at"); err != nil {
		t.Fatal(err)
	}

	if err := mat.ResetSchedule(ctx, f.tenantID, "sched1"); err != nil {
		t.Fatalf("ResetSchedule: %v", err)
	}

	now := time.Now().UnixMilli()
	var future []domain.EpgEntry
	for _, e := range queryEntries(t, f) {
		if e.EndAt > now {
			future = append(future, e)
		}
	}
	if len(future) == 0 || future[0].CatalogItemID != "m0" {
		t.Fatalf("chan1 was not reset: %+v", future)
	}
	if future[0].StartAt < now-1000 {
		t.Errorf("chan1 airing entry survived: starts %v", time.UnixMilli(future[0].StartAt))
	}
	var after2 []string
	if err := f.db.Query(ctx, &after2, "SELECT id FROM epg_entry WHERE channel_id = 'chan2' ORDER BY start_at"); err != nil {
		t.Fatal(err)
	}
	if len(after2) != len(before2) {
		t.Fatalf("chan2 row count changed: %d -> %d", len(before2), len(after2))
	}
	for i := range after2 {
		if after2[i] != before2[i] {
			t.Errorf("chan2 entry %d was touched by another schedule's reset", i)
		}
	}
}

func TestResetSchedule_NoChannelsIsNoOp(t *testing.T) {
	f := continuousSetup(t)
	f.createSchedule(t, "unused")
	mat := New(f.db, time.Hour)
	if err := mat.ResetSchedule(context.Background(), f.tenantID, "unused"); err != nil {
		t.Fatalf("ResetSchedule: %v", err)
	}
	if n := len(queryEntries(t, f)); n != 0 {
		t.Errorf("unrelated channel got %d entries", n)
	}
}

func TestContinuous_InteriorFrozenHoleIsHealed(t *testing.T) {
	f := continuousSetup(t)
	mat := New(f.db, 6*time.Hour)
	mat.SetFreezeMargin(150 * time.Minute)
	ctx := context.Background()
	if err := mat.Run(ctx); err != nil {
		t.Fatal(err)
	}
	first := queryEntries(t, f)
	if err := f.db.Exec(ctx, "DELETE FROM epg_entry WHERE id = ?", first[1].ID); err != nil {
		t.Fatal(err)
	}
	if err := mat.Run(ctx); err != nil {
		t.Fatal(err)
	}
	second := queryEntries(t, f)
	assertContiguous(t, second)
	assertRotation(t, second, 0)
	if second[0].ID != first[0].ID {
		t.Errorf("entry before the hole should stay frozen")
	}
	if second[1].ID == first[1].ID || second[1].CatalogItemID != "m1" {
		t.Errorf("hole not regenerated: %+v", second[1])
	}
}

func TestContinuous_HeadHoleIsHealed(t *testing.T) {
	f := continuousSetup(t)
	mat := New(f.db, 6*time.Hour)
	mat.SetFreezeMargin(150 * time.Minute)
	ctx := context.Background()
	if err := mat.Run(ctx); err != nil {
		t.Fatal(err)
	}
	first := queryEntries(t, f)
	// Nothing on air: the airing entry is gone.
	if err := f.db.Exec(ctx, "DELETE FROM epg_entry WHERE id = ?", first[0].ID); err != nil {
		t.Fatal(err)
	}
	if err := mat.Run(ctx); err != nil {
		t.Fatal(err)
	}
	now := time.Now().UnixMilli()
	var airing []domain.EpgEntry
	if err := f.db.Query(ctx, &airing, "SELECT "+epgEntryColumnsForTest+" FROM epg_entry WHERE channel_id = 'chan1' AND start_at <= ? AND end_at > ?", now, now); err != nil || len(airing) != 1 {
		t.Fatalf("nothing on air after the run: %v %v", airing, err)
	}
	assertContiguous(t, queryEntries(t, f))
}

func TestContinuous_CatalogOnlyChangeKeepsFrozenRows(t *testing.T) {
	f := continuousSetup(t)
	mat := New(f.db, 6*time.Hour)
	mat.SetFreezeMargin(150 * time.Minute)
	ctx := context.Background()
	if err := mat.Run(ctx); err != nil {
		t.Fatal(err)
	}
	first := queryEntries(t, f)
	if err := f.db.Exec(ctx, "UPDATE catalog_item SET title = 'Renamed' WHERE id = 'm0'"); err != nil {
		t.Fatal(err)
	}
	mat.Trigger()
	if err := mat.Run(ctx); err != nil {
		t.Fatal(err)
	}
	second := queryEntries(t, f)
	for i := 0; i < 3; i++ {
		if second[i].ID != first[i].ID {
			t.Errorf("entry %d regenerated by a catalog-only change", i)
		}
	}
}
